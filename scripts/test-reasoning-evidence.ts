import assert from 'node:assert/strict';
import {validateReasoningEvidence as validate,parseReasoningAnswer,reasoningProgress,matchesFormattingRequirement,reasoningActionConstraints,type ReasoningProbe} from './reasoning-evidence';
const paths=['a.py','b.py'];
const answer=(raw=false)=>paths.map(path=>`${path} | selected | ${raw?'markup_survives':'markup_escaped'}`).join('\n');
const probe=(path:string):ReasoningProbe=>({path,fn:'selected',kind:'html_reflection',status:'behavior_not_observed',observed:false,relevant:true});
assert.match(validate(answer(),paths,[])!,/no completed markup observation/);
for(const status of ['unsupported','error','timeout'])assert.match(validate(answer(),paths,[{...probe('a.py'),status}])!,/no completed/);
assert.match(validate(answer(),paths,[{...probe('a.py'),kind:'path_construction'}])!,/no completed/);
assert.match(validate(answer(),paths,[{...probe('a.py'),observed:true}])!,/no completed/);
assert.match(validate(answer(),paths,[probe('a.py')])!,/b.py/);
assert.match(validate(answer(true),paths,paths.map(probe))!,/contradicts/);
assert.equal(validate(answer(),paths,paths.map(probe)),null);
assert.match(validate('{',paths,paths.map(probe))!,/one line/);
assert.match(validate('a.py | selected | markup_escaped\na.py | selected | markup_escaped',paths,paths.map(probe))!,/exactly one/);
assert.equal(validate(answer(true),paths,paths.map(path=>({...probe(path),status:'behavior_observed',observed:true}))),null);
assert.match(validate(answer(),paths,[...paths.map(probe),{...probe('a.py'),status:'behavior_observed',observed:true}])!,/contradicts/);
assert.throws(()=>parseReasoningAnswer('a.py | false | Markup survives'));
assert.throws(()=>parseReasoningAnswer('a.py | selected | maybe'));
assert.match(validate('malformed',paths,[probe('a.py')])!,/b.py/);
const unrelated={...probe('a.py'),fn:'utility',status:'behavior_observed',observed:true,relevant:false};
const state=JSON.parse(reasoningProgress(paths,new Set(['a.py']),[unrelated,probe('b.py')]));
assert.deepEqual(state.pendingTests,['a.py']);
assert.deepEqual(state.modules[0].unrelatedFunctions,['utility']);
assert.equal(state.modules[0].observations.length,0);
assert.match(validate(answer(),paths,[unrelated,probe('b.py')])!,/a.py/);
assert.match(validate(answer().replaceAll('selected','utility'),paths,paths.map(probe))!,/No completed relevant observation/);
assert.equal(matchesFormattingRequirement({control_input:'ordinary',control_output:'<p>ordinary</p>'}),true);
assert.equal(matchesFormattingRequirement({control_input:'ordinary',control_output:'ORDINARY'}),false);
assert.equal(matchesFormattingRequirement({control_input:'ordinary',control_output:'<p>different</p>'}),false);
assert.equal(matchesFormattingRequirement(undefined),false);
console.log('Evidence, task relevance, function identity and classification validation passed');

const funcs=new Map(paths.map(path=>[path,['utility','selected']]));
assert.deepEqual(reasoningActionConstraints(paths,new Set(),funcs,[]).action,['read_file']);
assert.deepEqual(reasoningActionConstraints(paths,new Set(['a.py']),funcs,[]).action,['verify_source']);
assert.deepEqual(reasoningActionConstraints(paths,new Set(['a.py']),funcs,[unrelated]).query,['selected']);
assert.deepEqual(reasoningActionConstraints(paths,new Set(['a.py']),funcs,[probe('a.py')]).path,['b.py']);
const finalChoices=reasoningActionConstraints(paths,new Set(paths),funcs,paths.map(probe));
assert.deepEqual(finalChoices.action,['final']);
assert.equal(finalChoices.answer.length,4);
assert.ok(finalChoices.answer.includes(answer(true))&&finalChoices.answer.includes(answer(false)));
assert.throws(()=>reasoningActionConstraints(paths,new Set(['a.py']),new Map([['a.py',['utility']]]),[unrelated]),/Inspection incomplete/);
